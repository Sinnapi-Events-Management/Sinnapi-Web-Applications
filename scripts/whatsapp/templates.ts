// WhatsApp templates: check, seed, submit to Meta, and track approval.
//
// Everything is driven by ./catalog.ts. Run from the repo root:
//
//   deno run -A scripts/whatsapp/templates.ts check
//       Validate every template against Meta's rules. No network.
//   deno run -A scripts/whatsapp/templates.ts preview [trigger]
//       Print messages filled with the sample values, as a phone would show them.
//   deno run -A scripts/whatsapp/templates.ts sql > supabase/migrations/<ts>_whatsapp_templates.sql
//       The seed migration. Rows go in SWITCHED OFF (is_active = false).
//   deno run -A --env-file=supabase/functions/.env scripts/whatsapp/templates.ts submit
//       Create every template on Meta (skips ones that already exist).
//   deno run -A --env-file=supabase/functions/.env scripts/whatsapp/templates.ts status
//       Show Meta's review status for each, and print the SQL that switches on
//       the APPROVED ones. Run that SQL in the Supabase SQL editor.
//
// `submit` and `status` need WHATSAPP_BUSINESS_ACCOUNT_ID and an access token
// with the whatsapp_business_management permission.
import {
  FOOTER,
  SAMPLES,
  TEMPLATES,
  fullBody,
  templateName,
  type WhatsAppTemplateSpec,
} from './catalog.ts';

const LANGUAGE = 'en';
const CATEGORY = 'UTILITY';

interface Compiled {
  spec: WhatsAppTemplateSpec;
  name: string;
  /** Body with named blanks, stored in notification_templates.body_template. */
  namedBody: string;
  /** Body with Meta's numbered blanks. */
  metaBody: string;
  /** Blank names in number order: params[0] fills {{1}}. */
  params: string[];
}

const BLANK = /\{\{\s*([a-z0-9_]+)\s*\}\}/g;

function compile(spec: WhatsAppTemplateSpec): Compiled {
  const namedBody = fullBody(spec);
  const params: string[] = [];
  const metaBody = namedBody.replace(BLANK, (_, key: string) => {
    let index = params.indexOf(key);
    if (index === -1) index = params.push(key) - 1;
    return `{{${index + 1}}}`;
  });
  return { spec, name: templateName(spec.trigger), namedBody, metaBody, params };
}

/** Every problem Meta's validation or review would reject, per template. */
function problems(c: Compiled): string[] {
  const out: string[] = [];
  const body = c.namedBody;
  if (!/^[a-z0-9_]{1,512}$/.test(c.name)) out.push(`bad name "${c.name}"`);
  if (/\{\{/.test(c.spec.title)) out.push('title must not contain blanks');
  if (c.metaBody.length > 1024) out.push(`body is ${c.metaBody.length} chars (max 1024)`);
  if (/^\s*\{\{/.test(body) || /\}\}\s*$/.test(body)) out.push('body starts or ends with a blank');
  const touching = body.match(/\}\}[\s\p{P}]*\{\{/gu);
  if (touching) out.push(`blanks touch each other: ${touching.join(' | ')}`);
  const all = [...body.matchAll(BLANK)].map((m) => m[1]);
  const dupes = all.filter((k, i) => all.indexOf(k) !== i);
  if (dupes.length) out.push(`blank used more than once: ${[...new Set(dupes)].join(', ')}`);
  for (const key of c.params) if (!(key in SAMPLES)) out.push(`no sample for {{${key}}}`);
  // Meta rejects templates that are "mostly blanks". Their exact ratio is not
  // published; this is the conservative rule of thumb in their docs.
  const words = body.replace(BLANK, '').split(/\s+/).filter(Boolean).length;
  if (words < c.params.length * 2 + 1)
    out.push(`too few words (${words}) for ${c.params.length} blanks`);
  return out;
}

function compileAll(): Compiled[] {
  const compiled = TEMPLATES.map(compile);
  const seen = new Set<string>();
  let failed = false;
  if (FOOTER.length > 60) {
    console.error(`footer is ${FOOTER.length} chars (max 60)`);
    failed = true;
  }
  for (const c of compiled) {
    if (seen.has(c.spec.trigger)) {
      console.error(`${c.spec.trigger}: listed twice`);
      failed = true;
    }
    seen.add(c.spec.trigger);
    for (const p of problems(c)) {
      console.error(`${c.spec.trigger}: ${p}`);
      failed = true;
    }
  }
  if (failed) Deno.exit(1);
  return compiled;
}

function fill(c: Compiled): string {
  return c.namedBody.replace(BLANK, (_, key: string) => SAMPLES[key] ?? `[${key}]`);
}

const sqlText = (s: string) => `'${s.replace(/'/g, "''")}'`;

function seedSql(compiled: Compiled[]): string {
  const rows = compiled.map(
    (c) =>
      `  (${sqlText(c.spec.trigger)}, 'whatsapp', ${sqlText(c.spec.title)}, ${sqlText(c.namedBody)}, ` +
      `'${LANGUAGE}', false, ${sqlText(c.name)}, array[${c.params.map(sqlText).join(', ')}]::text[])`,
  );
  return `-- =====================================================================
-- Sinnapi — WhatsApp notifications, step 4: the templates.
--
-- GENERATED by \`deno run -A scripts/whatsapp/templates.ts sql\` from
-- scripts/whatsapp/catalog.ts. Edit the catalog and regenerate into a NEW
-- migration; never hand-edit this file.
--
-- One WhatsApp template per trigger that sends an email today (${compiled.length}).
-- \`body_template\` holds the readable copy with named blanks; what Meta
-- actually delivers is the approved template \`provider_template\`, whose
-- numbered blanks {{1}}, {{2}}, … are filled from the payload keys in
-- \`params\`, in order.
--
-- EVERY ROW GOES IN SWITCHED OFF. Meta must approve a template before it can
-- be sent; a row switched on before that would fail every send with 132001.
-- \`templates.ts status\` prints the update that switches on the approved ones.
--
-- Re-running updates the copy but never flips \`is_active\`: switching on is
-- the approval step's decision, not a deploy side effect.
-- =====================================================================

insert into public.notification_templates
  (trigger_key, channel, subject, body_template, locale, is_active, provider_template, params)
values
${rows.join(',\n')}
on conflict (trigger_key, channel, locale) do update
  set subject           = excluded.subject,
      body_template     = excluded.body_template,
      provider_template = excluded.provider_template,
      params            = excluded.params;
`;
}

// ── Meta Graph API ─────────────────────────────────────────────────────────

function metaEnv() {
  const waba = Deno.env.get('WHATSAPP_BUSINESS_ACCOUNT_ID')?.trim();
  const token = Deno.env.get('WHATSAPP_ACCESS_TOKEN')?.trim();
  const version = Deno.env.get('WHATSAPP_API_VERSION')?.trim() || 'v23.0';
  if (!waba || !token) {
    console.error(
      'Set WHATSAPP_BUSINESS_ACCOUNT_ID and WHATSAPP_ACCESS_TOKEN in supabase/functions/.env',
    );
    Deno.exit(1);
  }
  return { base: `https://graph.facebook.com/${version}/${waba}/message_templates`, token };
}

interface MetaTemplate {
  name: string;
  language: string;
  status: string;
  category: string;
  rejected_reason?: string;
}

async function listMeta(): Promise<MetaTemplate[]> {
  const { base, token } = metaEnv();
  const out: MetaTemplate[] = [];
  let url: string | undefined =
    `${base}?fields=name,language,status,category,rejected_reason&limit=200`;
  while (url) {
    const res: Response = await fetch(url, { headers: { Authorization: `Bearer ${token}` } });
    const json: { data: MetaTemplate[]; paging?: { next?: string }; error?: unknown } =
      await res.json();
    if (!res.ok) throw new Error(`list failed: ${JSON.stringify(json.error ?? json)}`);
    out.push(...json.data);
    url = json.paging?.next;
  }
  return out;
}

async function submit(compiled: Compiled[]) {
  const { base, token } = metaEnv();
  const existing = new Set(
    (await listMeta()).filter((t) => t.language === LANGUAGE).map((t) => t.name),
  );
  let created = 0;
  for (const c of compiled) {
    if (existing.has(c.name)) {
      console.log(`skip   ${c.name} (already on Meta)`);
      continue;
    }
    const res = await fetch(base, {
      method: 'POST',
      headers: { Authorization: `Bearer ${token}`, 'Content-Type': 'application/json' },
      body: JSON.stringify({
        name: c.name,
        language: LANGUAGE,
        category: CATEGORY,
        components: [
          {
            type: 'BODY',
            text: c.metaBody,
            ...(c.params.length
              ? { example: { body_text: [c.params.map((k) => SAMPLES[k])] } }
              : {}),
          },
          { type: 'FOOTER', text: FOOTER },
        ],
      }),
    });
    const json = await res.json();
    if (res.ok) {
      created++;
      console.log(
        `sent   ${c.name} → ${json.status ?? 'PENDING'}${json.category && json.category !== CATEGORY ? ` (Meta made it ${json.category})` : ''}`,
      );
    } else {
      const e = json.error ?? {};
      console.error(`FAILED ${c.name}: [${e.code}] ${e.error_user_msg ?? e.message}`);
    }
  }
  console.log(
    `\n${created} submitted. Approval usually takes minutes to a day; check with \`status\`.`,
  );
}

async function status(compiled: Compiled[]) {
  const meta = new Map(
    (await listMeta()).filter((t) => t.language === LANGUAGE).map((t) => [t.name, t]),
  );
  const approved: string[] = [];
  for (const c of compiled) {
    const t = meta.get(c.name);
    const label = t ? t.status : 'NOT SUBMITTED';
    const extra =
      t?.rejected_reason && t.rejected_reason !== 'NONE' ? ` — ${t.rejected_reason}` : '';
    const recat = t && t.category !== CATEGORY ? ` (category ${t.category}!)` : '';
    console.log(`${label.padEnd(14)} ${c.name}${extra}${recat}`);
    if (t?.status === 'APPROVED' && t.category === CATEGORY) approved.push(c.name);
  }
  console.log(`\n${approved.length}/${compiled.length} approved as ${CATEGORY}.`);
  if (approved.length) {
    console.log('\n-- Run in the Supabase SQL editor to switch the approved templates on:');
    console.log(
      `update public.notification_templates set is_active = true\n where channel = 'whatsapp'\n   and provider_template in (\n${approved.map((n) => `     ${sqlText(n)}`).join(',\n')}\n   );`,
    );
  }
}

// ── CLI ────────────────────────────────────────────────────────────────────

const [command, arg] = Deno.args;
const compiled = compileAll();

switch (command) {
  case 'check':
    console.log(`OK — ${compiled.length} templates pass every check.`);
    break;
  case 'preview':
    for (const c of compiled.filter((c) => !arg || c.spec.trigger === arg)) {
      console.log(`── ${c.name}  [${c.params.join(', ')}]\n${fill(c)}\n   ─ ${FOOTER}\n`);
    }
    break;
  case 'sql':
    console.log(seedSql(compiled));
    break;
  case 'submit':
    await submit(compiled);
    break;
  case 'status':
    await status(compiled);
    break;
  default:
    console.error('usage: templates.ts check | preview [trigger] | sql | submit | status');
    Deno.exit(1);
}
